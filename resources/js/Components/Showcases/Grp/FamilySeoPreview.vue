<script setup lang="ts">
import { computed } from "vue"
import WebpageSeoPreview from "@/Components/DataDisplay/WebpageSeoPreview.vue"
import { ctrans } from "@/Composables/useTrans"

export interface FamilySeoPreviewData {
    domain: string
    title: string | null
    description: string | null
    url: string | null
    use_title_prefix_suffix: boolean
    title_prefix: string | null
    title_suffix: string | null
    website_title_prefix: string | null
    website_title_suffix: string | null
    share_image: { url: string | null, alt: string | null }
    structured_data: string
}

const props = withDefaults(defineProps<{
    preview: FamilySeoPreviewData
    typed?: Record<string, string | boolean>
    subtitle?: string
}>(), {
    typed: () => ({}),
})

const TITLE_LENGTH = { min: 20, max: 60 }
const DESCRIPTION_LENGTH = { min: 70, max: 160 }

const typedOr = <T,>(field: string, saved: T) => (field in props.typed ? props.typed[field] : saved) as T

const title = computed(() => {
    const pageTitle = typedOr("title", props.preview.title ?? "")
    if (!typedOr("use_title_prefix_suffix", props.preview.use_title_prefix_suffix)) {
        return pageTitle
    }

    const prefix = typedOr("webpage_title_prefix", props.preview.title_prefix ?? "") || props.preview.website_title_prefix
    const suffix = typedOr("webpage_title_suffix", props.preview.title_suffix ?? "") || props.preview.website_title_suffix

    return [prefix, pageTitle, suffix].filter(Boolean).join(" ")
})
const description = computed(() => typedOr("description", props.preview.description ?? ""))
const url = computed(() => typedOr("url", props.preview.url ?? ""))

const lengthClass = (length: number, limits: { min: number, max: number }) => length >= limits.min && length <= limits.max ? "text-green-700" : "text-red-600"

const urlHint = computed(() => {
    if (/^[a-z0-9]+(?:[-/][a-z0-9]+)*$/.test(url.value)) {
        return null
    }

    return url.value.includes("_") ? ctrans("Use hyphens instead of underscores in the URL.") : ctrans("Use only lowercase letters, numbers and hyphens in the URL.")
})

const structuredDataJson = computed(() => typedOr("structured_data", props.preview.structured_data) || null)
const structuredDataTypes = computed(() => {
    try {
        const parsed = JSON.parse(structuredDataJson.value ?? "")
        const nodes = [parsed, ...(parsed?.["@graph"] ?? [])].flat()

        return [...new Set(nodes.flatMap((node) => [node?.["@type"]].flat()).filter((type): type is string => typeof type === "string"))]
    } catch {
        return []
    }
})
</script>

<template>
    <section class="flex flex-col gap-3 rounded-lg border border-gray-200 bg-white p-4 shadow-md">
        <div class="flex flex-wrap items-center justify-between gap-2">
            <h2 class="font-semibold text-gray-900">{{ ctrans("Preview") }}</h2>
            <span class="text-xs text-gray-500">{{ subtitle ?? ctrans("Current values on the live page") }}</span>
        </div>

        <WebpageSeoPreview
            :searchUrl="`${preview.domain}/${url}`"
            :domain="preview.domain"
            :title="title"
            :description="description"
            :shareImage="preview.share_image"
            :structuredDataJson="structuredDataJson"
            :structuredDataTypes="structuredDataTypes"
            :structuredDataNote="ctrans('Custom JSON-LD of the page. Product / ProductGroup are generated by the system on top.')" />

        <dl class="flex flex-col gap-1 text-xs">
            <div class="flex items-center justify-between gap-2">
                <dt class="text-gray-600">{{ ctrans("Title length") }}</dt>
                <dd class="font-semibold tabular-nums" :class="lengthClass(title.length, TITLE_LENGTH)">{{ title.length }} / {{ TITLE_LENGTH.max }}</dd>
            </div>
            <div class="flex items-center justify-between gap-2">
                <dt class="text-gray-600">{{ ctrans("Description length") }}</dt>
                <dd class="font-semibold tabular-nums" :class="lengthClass(description.length, DESCRIPTION_LENGTH)">{{ description.length }} / {{ DESCRIPTION_LENGTH.max }}</dd>
            </div>
        </dl>
        <p v-if="urlHint" class="text-xs font-medium text-amber-700">{{ urlHint }}</p>

        <slot />
    </section>
</template>
